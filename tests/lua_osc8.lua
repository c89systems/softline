local softline = require("softline")
local sl = assert(softline.new())
local info = assert(sl:get_osc8_info())
assert(info.mode == softline.OSC8_OFF and not info.enabled)
assert(type(info.detected) == "boolean")
assert(not sl:set_osc8_mode(99))
assert(not sl:set_osc8_mode(4294967297))
assert(softline.OSC8_MAX_BYTES == 8192)
assert(sl:get_osc8_info().mode == softline.OSC8_OFF)
assert(sl:set_osc8_mode(softline.OSC8_AUTO))
assert(sl:get_osc8_info().enabled == sl:get_osc8_info().detected)
assert(sl:set_osc8_mode(softline.OSC8_ON))
assert(sl:get_osc8_info().enabled)
assert(sl:output_stream_begin())
assert(not sl:set_osc8_mode(softline.OSC8_OFF))
local text = "\27]8;id=lua;https://example.org/\27\\label\27]8;;\7\n"
for i = 1, #text do assert(sl:output_stream_write(text:sub(i, i))) end
assert(not sl:output_stream_write("\27]52;c;secret\7"))
assert(sl:output_stream_write("safe\n"))
assert(sl:output_stream_end())
sl:close()
local configured = assert(softline.new({osc8_mode = softline.OSC8_ON}))
assert(configured:get_osc8_info().mode == softline.OSC8_ON)
assert(configured:get_osc8_info().enabled)
configured:close()
assert(not pcall(softline.new, {osc8_mode = 99}))
assert(not pcall(softline.new, {osc8_mode = 4294967297}))
